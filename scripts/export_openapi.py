"""Export and verify the committed, deterministic API v1 OpenAPI document."""

from __future__ import annotations

import argparse
import json
import os
import tempfile
from pathlib import Path
from typing import cast

from llm_eval_control_plane.api.app import create_app
from llm_eval_control_plane.api.security import (
    AuthenticationConfiguration,
    ControlPlaneAuthorizer,
    ControlPlaneScope,
    PrincipalConfiguration,
)
from llm_eval_control_plane.application.control_plane import (
    ControlPlaneRepository,
    ControlPlaneService,
    EvaluationExecutor,
)
from llm_eval_control_plane.observability import Observability

_REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = _REPOSITORY_ROOT / "docs" / "openapi-v1.json"


def rendered_openapi() -> bytes:
    """Build canonical presentation bytes without a database or credentials."""
    unavailable_dependency = object()
    service = ControlPlaneService(
        repository=cast(ControlPlaneRepository, unavailable_dependency),
        executor=cast(EvaluationExecutor, unavailable_dependency),
    )
    authorizer = ControlPlaneAuthorizer(
        AuthenticationConfiguration(
            schema_version="control-plane-auth/v1",
            project_id="project-documentation",
            principals=(
                PrincipalConfiguration(
                    principal_id="documentation-only",
                    token_digest="sha256:" + ("0" * 64),
                    scopes=tuple(
                        sorted(ControlPlaneScope, key=lambda item: item.value)
                    ),
                ),
            ),
        )
    )
    document = create_app(
        service=service,
        authorizer=authorizer,
        telemetry=Observability(service="api"),
    ).openapi()
    return (
        json.dumps(
            document,
            ensure_ascii=False,
            indent=2,
            sort_keys=True,
        )
        + "\n"
    ).encode("utf-8")


def artifact_is_current(path: Path = DEFAULT_OUTPUT) -> bool:
    """Return whether an artifact exactly matches the generated bytes."""
    try:
        return path.read_bytes() == rendered_openapi()
    except OSError:
        return False


def write_artifact(path: Path = DEFAULT_OUTPUT) -> None:
    """Atomically replace the generated artifact."""
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary_name = tempfile.mkstemp(
        dir=path.parent,
        prefix=f".{path.name}.",
        suffix=".tmp",
    )
    temporary = Path(temporary_name)
    try:
        if os.name != "nt":  # pragma: no branch - POSIX artifact permissions
            os.fchmod(descriptor, 0o644)
        with os.fdopen(descriptor, "wb") as stream:
            descriptor = -1
            stream.write(rendered_openapi())
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if descriptor >= 0:
            os.close(descriptor)
        temporary.unlink(missing_ok=True)


def main(arguments: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Export the deterministic API v1 OpenAPI artifact.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when the committed artifact differs from the generated schema",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help=argparse.SUPPRESS,
    )
    options = parser.parse_args(arguments)
    output = cast(Path, options.output)
    if options.check:
        if artifact_is_current(output):
            print("OpenAPI artifact is current")
            return 0
        print("OpenAPI artifact is out of date; run scripts/export_openapi.py")
        return 1
    write_artifact(output)
    print("Exported docs/openapi-v1.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
